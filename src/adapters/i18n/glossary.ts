function localizeDuration(value: string): string | null {
  const match = /^(\d+)\s+(hour|hours|day|days|week|weeks|month|months|year|years)$/i.exec(
    value.trim(),
  );
  if (!match) return null;
  const count = match[1]!;
  const unit = match[2]!.toLowerCase();
  const n = Number(count);
  const ruUnit = russianUnit(unit, n);
  return `${count} ${ruUnit}`;
}

function russianUnit(unit: string, n: number): string {
  const forms: Record<string, [string, string, string]> = {
    hour: ["час", "часа", "часов"],
    hours: ["час", "часа", "часов"],
    day: ["день", "дня", "дней"],
    days: ["день", "дня", "дней"],
    week: ["неделя", "недели", "недель"],
    weeks: ["неделя", "недели", "недель"],
    month: ["месяц", "месяца", "месяцев"],
    months: ["месяц", "месяца", "месяцев"],
    year: ["год", "года", "лет"],
    years: ["год", "года", "лет"],
  };
  const triple = forms[unit] ?? [UNIT_ONE[unit] ?? unit, UNIT_ONE[unit] ?? unit, UNIT_ONE[unit] ?? unit];
  const abs = Math.abs(n) % 100;
  const last = abs % 10;
  if (abs > 10 && abs < 20) return triple[2]!;
  if (last === 1) return triple[0]!;
  if (last >= 2 && last <= 4) return triple[1]!;
  return triple[2]!;
}

function localizeToken(token: string): string {
  const trimmed = token.trim();
  if (!trimmed) return trimmed;
  const direct = TOKENS[trimmed.toLowerCase()];
  if (direct) return direct;
  return trimmed;
}

export function localizeValue(
  value: string,
  locale: Locale,
  options?: { fieldKey?: string; entityId?: number },
): string {
  if (locale === "en") return value;
  if (options?.fieldKey === "opening_crawl" && options.entityId != null) {
    const crawl = OPENING_CRAWLS_RU[options.entityId];
    if (crawl) return crawl;
  }
  const duration = localizeDuration(value);
  if (duration) return duration;

  if (value.includes(",")) {
    return value
      .split(",")
      .map((part) => localizeToken(part))
      .join(", ");
  }
  if (value.includes("/")) {
    return value
      .split("/")
      .map((part) => localizeToken(part))
      .join("/");
  }
  return localizeToken(value);
}
